import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const base = process.env.STUDIO_CHECK_URL ?? 'http://127.0.0.1:3080';
const studio = '/home/ubuntu/compileverse/studio';
const credentials = JSON.parse(await fs.readFile(studio + '/access.json', 'utf8'));
const login = await fetch(base + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(credentials) });
assert.equal(login.status, 200); const { token } = await login.json();
const call = async (url, options = {}) => {
  const response = await fetch(base + url, { ...options, headers: { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' } });
  const data = await response.json(); assert.ok(response.ok, `${url}: ${response.status} ${JSON.stringify(data)}`); return data;
};
const name = '手机修订验收-' + Date.now(), directory = '/home/ubuntu/compileverse/inputs/' + name;
const first = await call('/api/conversations', { method: 'POST', body: JSON.stringify({ provider: 'codex', projectName: name, title: 'Codex 目录验收', cwd: { root: 'inputs', path: '' }, createDirectory: true }) });
assert.equal(first.projectPath, directory);
await fs.writeFile(directory + '/source-must-survive.txt', 'keep-source');
const second = await call('/api/conversations', { method: 'POST', body: JSON.stringify({ provider: 'claude', projectName: '手机验收改名', title: 'Claude 同目录验收', cwd: { root: 'inputs', path: name }, createDirectory: false }) });
assert.equal(second.projectPath, directory);
const recent = await call('/api/cloud/providers/sessions/recent?limit=100');
for (const id of [first.sessionId, second.sessionId]) assert.equal(recent.data.conversations.find(value => value.sessionId === id)?.projectDisplayName, '手机验收改名');
const details = await call('/api/cloud/providers/sessions/' + second.sessionId);
assert.equal(details.data.project.fullPath, directory);
for (const id of [first.sessionId, second.sessionId]) await call('/api/conversations/' + id, { method: 'DELETE' });
const after = await call('/api/cloud/providers/sessions/recent?limit=100');
assert.ok(after.data.conversations.every(value => ![first.sessionId, second.sessionId].includes(value.sessionId)));
assert.equal(await fs.readFile(directory + '/source-must-survive.txt', 'utf8'), 'keep-source');
await fs.unlink(directory + '/source-must-survive.txt'); await fs.rmdir(directory);
await call('/api/cloud/projects/' + encodeURIComponent(details.data.project.projectId), { method: 'DELETE' });
const report = { passed: true, version: (await call('/api/health')).version, date: new Date().toISOString(), checks: ['real Codex selected project directory', 'real Claude existing directory', 'project display name persists in upstream catalog', 'both sessions deleted from active list', 'source file preserved by session deletion'], modelInference: false };
await fs.writeFile(studio + '/state/revision-02.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
