import { test } from 'node:test';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { CodexBridge } from '../server/codex.ts';
import { until } from './helpers.ts';

test('Codex stdio handshake, explicit approval/decline, durable history and resume', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'cv-codex-test-'));
  const bridge = new CodexBridge(dir, process.execPath, [path.resolve('tests/codex-fixture.mjs')]);
  t.after(async () => { bridge.close(); await new Promise(r => setTimeout(r, 30)); await fs.rm(dir, { recursive: true, force: true }); });
  bridge.register('session-one', dir);
  await bridge.send('session-one', '检查命令');
  await until(() => bridge.approvals.size === 1);
  const event = [...bridge.approvals.values()][0].event;
  assert.equal(event.toolName, '执行命令');
  assert.equal(bridge.sessions.get('session-one')!.processing, true);
  assert.equal(bridge.approve(String(event.requestId), false), true);
  await until(() => !bridge.sessions.get('session-one')!.processing);
  assert.ok(bridge.history('session-one').messages.some(e => e.kind === 'text' && e.content === '已拒绝'));
  await bridge.send('session-one', '再次检查');
  await until(() => bridge.approvals.size === 1);
  bridge.approve(String([...bridge.approvals.values()][0].event.requestId), true);
  await until(() => !bridge.sessions.get('session-one')!.processing);
  assert.ok(bridge.history('session-one').messages.some(e => e.kind === 'text' && e.content === '已批准'));
  const restored = new CodexBridge(dir, process.execPath, [path.resolve('tests/codex-fixture.mjs')]);
  assert.equal(restored.sessions.get('session-one')!.threadId, 'fixture-thread');
  assert.ok(restored.history('session-one').messages.length >= 8);
  await restored.send('session-one', '恢复后继续');
  await until(() => restored.approvals.size === 1);
  await restored.abort('session-one');
  await until(() => !restored.sessions.get('session-one')!.processing);
  await restored.archive('session-one'); restored.remove('session-one');
  assert.equal(restored.has('session-one'), false);
  const deleted = new CodexBridge(dir, process.execPath, [path.resolve('tests/codex-fixture.mjs')]);
  assert.equal(deleted.has('session-one'), false); deleted.close();
  restored.close();
});
